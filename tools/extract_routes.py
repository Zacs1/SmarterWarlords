"""Turns the route network a live round logged to its RPT into commander/swlc/maps/<world>_routes.sqf.

Usage: python tools/extract_routes.py <rpt> [--out <file>]

The commander writes C_ROUTE lines when it generates a network at mission start. With the file in place,
later rounds on that map load it and skip generating. Uses the last complete dump in the RPT.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

LINE = re.compile(r"SWL\|C_ROUTE\|(.*)$")
PER_LINE = 20


def fields(body: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for part in body.strip().strip('"').split("|"):
        key, sep, value = part.partition("=")
        if sep:
            out[key] = value
    return out


def pairs(data: str) -> list[list[int]]:
    result = []
    for item in data.split(";"):
        if item:
            a, b = item.split(",")
            result.append([round(float(a)), round(float(b))])
    return result


def read_dumps(rpt: Path) -> list[dict]:
    """Every complete dump in the RPT, oldest first."""
    dumps = []
    current = None
    with rpt.open(encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            match = LINE.search(raw)
            if not match:
                continue
            f = fields(match.group(1))
            action = f.get("action")
            if action == "dump_begin":
                current = {"world": f["world"], "hop": int(float(f["hop"])), "nodes": {}, "edges": {}, "want_nodes": int(f["nodes"]), "want_edges": int(f["edges"])}
            elif current is not None and action in ("nodes", "edges"):
                current[action][int(f["from"])] = pairs(f.get("data", ""))
            elif current is not None and action == "dump_end":
                current["complete"] = True
                dumps.append(current)
                current = None
    return dumps


def flatten(chunks: dict[int, list[list[int]]]) -> list[list[int]]:
    items: list[list[int]] = []
    for start in sorted(chunks):
        if start != len(items):
            raise ValueError(f"chunk starting at {start} does not follow {len(items)} items")
        items.extend(chunks[start])
    return items


def block(items: list[list[int]]) -> str:
    lines = []
    for i in range(0, len(items), PER_LINE):
        lines.append("\t\t" + ",".join(f"[{a},{b}]" for a, b in items[i : i + PER_LINE]))
    return ",\n".join(lines)


def write_routes(dump: dict, nodes: list[list[int]], edges: list[list[int]], source: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    text = (
        f"// Route network for {dump['world']}. Generated by tools/extract_routes.py from {source.name}. Do not edit.\n"
        f"// [world, hop metres, nodes [x, y], edges [a, b]]\n"
        f'["{dump["world"]}", {dump["hop"]},\n\t[\n{block(nodes)}\n\t],\n\t[\n{block(edges)}\n\t]\n]\n'
    )
    out.write_text(text, encoding="ascii", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("rpt", type=Path)
    parser.add_argument("--out", type=Path, help="output file (default: commander/swlc/maps/<world>_routes.sqf)")
    args = parser.parse_args()

    dumps = read_dumps(args.rpt)
    if not dumps:
        print(f"No complete route dump in {args.rpt}. A round must run on the map, with no stored network, until the C_ROUTE dump_end line.", file=sys.stderr)
        return 1
    dump = dumps[-1]
    nodes = flatten(dump["nodes"])
    edges = flatten(dump["edges"])
    if len(nodes) != dump["want_nodes"] or len(edges) != dump["want_edges"]:
        print(f"Dump is incomplete: {len(nodes)}/{dump['want_nodes']} nodes, {len(edges)}/{dump['want_edges']} edges.", file=sys.stderr)
        return 1
    bad = [e for e in edges if not (0 <= e[0] < len(nodes) and 0 <= e[1] < len(nodes))]
    if bad:
        print(f"{len(bad)} edges refer to nodes that don't exist, for example {bad[0]}.", file=sys.stderr)
        return 1

    root = Path(__file__).resolve().parent.parent
    out = args.out or root / "commander" / "swlc" / "maps" / f"{dump['world']}_routes.sqf"
    write_routes(dump, nodes, edges, args.rpt, out)
    print(f"Wrote {out}: {dump['world']}, {len(nodes)} nodes, {len(edges)} edges.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
